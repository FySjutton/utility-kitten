
import fs from "node:fs";
import path from "node:path";
import { spawn } from "node:child_process";
import { fileURLToPath } from "node:url";

const PROJECT_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const TOOLS_DIR = path.join(PROJECT_ROOT, "app", "(tools)");
const OUT_FILE = path.join(PROJECT_ROOT, "lib", "tools", "registry.generated.ts");

const isRouteGroup = (name) => name.startsWith("(") && name.endsWith(")");
const toPosix = (p) => p.split(path.sep).join("/");

function urlPathOf(relDir) {
    return toPosix(relDir).split("/").filter((s) => s && !isRouteGroup(s)).join("/");
}

function scan() {
    const tools = [];
    const categories = [];
    const errors = [];

    function walk(absDir) {
        const entries = fs.readdirSync(absDir, { withFileTypes: true });
        const files = new Set(entries.filter((e) => e.isFile()).map((e) => e.name));
        const relDir = path.relative(TOOLS_DIR, absDir);
        const relShown = `app/(tools)/${toPosix(relDir)}`;

        if (relDir) {
            const hasMeta = files.has("meta.ts");
            const hasCategory = files.has("category.ts");
            const hasPage = files.has("page.tsx");
            const urlPath = urlPathOf(relDir);
            const importPath = `@/app/(tools)/${toPosix(relDir)}`;

            if (hasMeta && hasCategory) {
                errors.push(`${relShown}: have both a meta.ts and a category.ts. Choose one.`);
            } else if (hasMeta) {
                if (!hasPage) errors.push(`${relShown}: meta.ts exists but page.tsx is missing.`);
                tools.push({ urlPath, importPath: `${importPath}/meta`, file: `${relShown}/meta.ts` });
            } else if (hasCategory) {
                categories.push({ urlPath, importPath: `${importPath}/category`, file: `${relShown}/category.ts` });
            } else if (hasPage) {
                errors.push(`${relShown}: page.tsx is missing meta.ts (tool) or category.ts. Run \`npm run new:tool\`.`);
            }
        }

        for (const e of entries) {
            if (e.isDirectory() && !e.name.startsWith("_") && !e.name.startsWith(".")) {
                walk(path.join(absDir, e.name));
            }
        }
    }

    if (fs.existsSync(TOOLS_DIR)) walk(TOOLS_DIR);

    for (const item of [...tools, ...categories]) {
        const src = fs.readFileSync(path.join(PROJECT_ROOT, item.file), "utf8");
        if (!/export\s+default\b/.test(src)) errors.push(`${item.file}: is missing \`export default\`.`);
    }

    const seen = new Map();
    for (const item of [...categories, ...tools]) {
        if (seen.has(item.urlPath)) errors.push(`URL /${item.urlPath} is used by both ${seen.get(item.urlPath)} and ${item.file}.`);
        else seen.set(item.urlPath, item.file);
    }

    const categoryPaths = new Set(categories.map((c) => c.urlPath));
    for (const item of [...categories, ...tools]) {
        const parent = item.urlPath.split("/").slice(0, -1).join("/");
        const isTool = tools.includes(item);
        if (!parent) {
            if (isTool) errors.push(`${item.file}: tools needs to lay in a category, not directly in app/(tools).`);
        } else if (!categoryPaths.has(parent)) {
            errors.push(`${item.file}: parent /${parent} is not a category (category.ts missing).`);
        }
    }

    const byPath = (a, b) => a.urlPath.localeCompare(b.urlPath);
    return { tools: tools.sort(byPath), categories: categories.sort(byPath), errors };
}

function render({ tools, categories }) {
    const lines = [
        "// AUTO GENERATED by scripts/generate-registry.mjs. DO NOT MANUALLY EDIT.",
        "// Edit in meta.ts / category.ts instead.",
        "",
        'import type { CategoryMeta, ToolMeta } from "./types";',
    ];
    categories.forEach((c, i) => lines.push(`import c${i} from "${c.importPath}";`));
    tools.forEach((t, i) => lines.push(`import t${i} from "${t.importPath}";`));
    lines.push("");
    lines.push("export const categoryEntries: { path: string; meta: CategoryMeta }[] = [");
    categories.forEach((c, i) => lines.push(`    { path: ${JSON.stringify(c.urlPath)}, meta: c${i} },`));
    lines.push("];");
    lines.push("");
    lines.push("export const toolEntries: { path: string; meta: ToolMeta }[] = [");
    tools.forEach((t, i) => lines.push(`    { path: ${JSON.stringify(t.urlPath)}, meta: t${i} },`));
    lines.push("];");
    lines.push("");
    return lines.join("\n");
}

export function generate() {
    const result = scan();
    if (result.errors.length) {
        console.error("\n✖ Tool-registry has wrong:\n" + result.errors.map((e) => "  - " + e).join("\n") + "\n");
        return false;
    }
    const output = render(result);
    const current = fs.existsSync(OUT_FILE) ? fs.readFileSync(OUT_FILE, "utf8") : null;
    if (current !== output) {
        fs.mkdirSync(path.dirname(OUT_FILE), { recursive: true });
        fs.writeFileSync(OUT_FILE, output);
        console.log(`✓ Tool-registry: ${result.categories.length} categories, ${result.tools.length} tools`);
    }
    return true;
}

function watch() {
    let timer;
    fs.watch(TOOLS_DIR, { recursive: true }, (_event, filename) => {
        if (filename && !/(^|[\\/])(meta|category|page)\.tsx?$/.test(filename) && path.extname(filename) !== "") return;
        clearTimeout(timer);
        timer = setTimeout(() => generate(), 100);
    });
    console.log("Watching app/(tools) for new tools ...");
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
    const args = process.argv.slice(2);
    const sep = args.indexOf("--");
    const flags = sep === -1 ? args : args.slice(0, sep);
    const command = sep === -1 ? [] : args.slice(sep + 1);

    const ok = generate();

    if (!flags.includes("--watch")) {
        process.exit(ok ? 0 : 1);
    }

    fs.mkdirSync(TOOLS_DIR, { recursive: true });
    watch();

    if (command.length) {
        const child = spawn(command[0], command.slice(1), {
            stdio: "inherit",
            shell: process.platform === "win32",
        });
        const stop = (signal) => child.kill(signal);
        process.on("SIGINT", stop);
        process.on("SIGTERM", stop);
        child.on("exit", (code) => process.exit(code ?? 0));
    }
}
